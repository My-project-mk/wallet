CREATE TABLE wallets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id      UUID           NOT NULL UNIQUE,
    currency       VARCHAR(3)     NOT NULL,
    balance        NUMERIC(19, 2) NOT NULL,
    system_account BOOLEAN        NOT NULL DEFAULT FALSE,
    create_date    TIMESTAMP      NOT NULL,
    update_date    TIMESTAMP,
    -- Balance guard enforced by the database as a last line of defence.
    -- System (treasury) accounts are the counter-party of deposits and may go negative.
    CONSTRAINT wallets_balance_non_negative CHECK (system_account OR balance >= 0)
);

CREATE UNIQUE INDEX wallets_one_treasury_per_currency ON wallets (currency) WHERE system_account;

CREATE TABLE transfers (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id             UUID           NOT NULL UNIQUE,
    idempotency_key       UUID UNIQUE,
    type                  VARCHAR(20)    NOT NULL,
    source_wallet_id      BIGINT         NOT NULL REFERENCES wallets (id),
    destination_wallet_id BIGINT         NOT NULL REFERENCES wallets (id),
    amount                NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    currency              VARCHAR(3)     NOT NULL,
    create_date           TIMESTAMP      NOT NULL,
    update_date           TIMESTAMP,
    CHECK (source_wallet_id <> destination_wallet_id)
);

CREATE TABLE ledger_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     UUID           NOT NULL UNIQUE,
    transfer_id   BIGINT         NOT NULL REFERENCES transfers (id),
    wallet_id     BIGINT         NOT NULL REFERENCES wallets (id),
    entry_type    VARCHAR(10)    NOT NULL,
    amount        NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    balance_after NUMERIC(19, 2) NOT NULL,
    create_date   TIMESTAMP      NOT NULL,
    update_date   TIMESTAMP
);

CREATE INDEX ledger_entries_wallet_recent ON ledger_entries (wallet_id, id DESC);

CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key UUID        NOT NULL UNIQUE,
    request_hash    VARCHAR(64) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    locked_at       TIMESTAMP   NOT NULL,
    create_date     TIMESTAMP   NOT NULL
);

